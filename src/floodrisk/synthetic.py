"""合成数据发生器（SYNTHETIC ONLY）。

!! 警告 !!
本模块生成的每一个数字都是**编造的**，只用于验证程序能否跑通。
坐标原点被刻意放在几内亚湾附近 (0°, 0°)，地名、行政区、水浸黑点全部虚构，
从几何上就与香港无关 —— 这样任何人看到图都不会误认。

使用约束（已写进代码与旁挂文件）：
- 输出目录会生成 ``*.provenance.json``，io.py 读取后把 SYNTHETIC 标记带进
  所有 metrics / manifest；
- 指标即使漂亮到 AUC=0.98，也不能进报告、不能进答辩 PPT、不能作为"模型效果"证据。

数据生成机制（写清楚，避免以后自己都忘了）
------------------------------------------
1. 地形：南侧为虚拟海岸线，向北高程抬升；人口在中纬度带达峰（虚构的"沿海居住带"）。
2. 时间序列（issue_time 锚定）：行时间戳 = 预测发起时刻；按小时步长；
   降雨用"基础噪声 + 随机暴雨事件"；天文潮 tide_ast 是确定性半日潮
   （周期 12.42h、全局相位，任意未来时刻可精确计算）；实测潮位 = 天文潮 +
   与降雨强度相关的风暴增水（沿海网格信号更强）；风速由降雨驱动。
3. 标签：先算逐小时瞬时风险 logit（雨量饱和 + 潮位顶托 + 低洼 + 排水缺口 +
   雨潮交互 + 网格随机效应），再聚合成 [t, t+window) 的窗口标签，
   末端 window-1 步右删失；截距按目标**窗口标签率**反解。
   该基准率是**人为设定**的，不是从现实学到的 —— 这一点必须写进报告
   （真实数据的正例率由历史记录决定，通常远低于此）。
4. 缺报：gap_fraction 比例的 (grid, hour) 行被抽走，模拟真实数据的空洞。
   没有它，"按行位移"和"按时间位移"永远一致，泄漏闸门的数值校验就是摆设。
"""

from __future__ import annotations

import json
import math
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np
import pandas as pd

PROVENANCE_NOTE = (
    "SYNTHETIC DATA GENERATED BY floodrisk.synthetic — 纯程序测试用途，"
    "坐标与地名完全虚构，禁止冒充真实香港数据，禁止引用其任何指标或图件"
)

# 虚构坐标原点：几内亚湾 (0°, 0°)，与香港无任何关系
_ORIGIN_LON = 0.0
_ORIGIN_LAT = 0.0
_KM_PER_DEG_LON = 111.32
_KM_PER_DEG_LAT = 110.57


# ---------------------------------------------------------------------------
# 基础场
# ---------------------------------------------------------------------------
def generate_grids(
    n_grids: int = 64,
    *,
    cell_km: float = 0.8,
    seed: int = 42,
) -> pd.DataFrame:
    """生成虚构网格的地形/承灾体属性（静态部分）。"""
    rng = np.random.default_rng(seed)
    side = int(math.ceil(math.sqrt(n_grids)))
    rows, cols = np.meshgrid(np.arange(side), np.arange(side), indexing="ij")
    rows = rows.ravel()[:n_grids]
    cols = cols.ravel()[:n_grids]

    x_km = cols * cell_km
    y_km = rows * cell_km
    # 海岸线在 y=0（南侧），距离即 y
    coast_dist = y_km + rng.normal(0, 0.18, n_grids)
    coast_dist = np.clip(coast_dist, 0.02, None)

    elevation = 55.0 * (1.0 - np.exp(-coast_dist / 1.5)) + rng.normal(0, 3.5, n_grids)
    elevation = np.clip(elevation, 0.5, 120.0)

    slope = 2.0 + 7.0 * np.exp(-coast_dist / 2.2) + rng.normal(0, 0.8, n_grids)
    slope = np.clip(slope, 0.1, 45.0)

    # 排水设计能力：市中心沿海偏弱（虚构设定，不是香港事实）
    drainage = 30.0 + 28.0 * np.clip(elevation / 40.0, 0, 1) + rng.normal(0, 4.0, n_grids)
    drainage = np.clip(drainage, 12.0, 110.0)

    pop = 800.0 + 12000.0 * np.exp(-((coast_dist - 1.2) ** 2) / (2 * 1.1**2))
    pop = np.clip(pop * np.exp(rng.normal(0, 0.25, n_grids)), 50.0, None)

    # 脆弱度是合成构造：人口越密、地势越低越脆弱
    vuln = (
        0.12
        + 0.50 * np.sqrt(pop / 14000.0)
        + 0.35 * (1.0 - elevation / 55.0)
        + rng.normal(0, 0.06, n_grids)
    )
    vuln = np.clip(vuln, 0.0, 1.0)

    # 空间分块：每 2×2 个网格归一块，模拟行政区式划分（保证块内相邻、块间不重叠）
    block_col = cols // 2
    block_row = rows // 2
    block_id = [f"Z{br}{bc}" for br, bc in zip(block_row, block_col)]

    grids = pd.DataFrame(
        {
            "grid_id": [f"G{i:04d}" for i in range(n_grids)],
            "x_km": x_km.round(4),
            "y_km": y_km.round(4),
            "lon": (_ORIGIN_LON + x_km / _KM_PER_DEG_LON).round(6),
            "lat": (_ORIGIN_LAT + y_km / _KM_PER_DEG_LAT).round(6),
            "elevation": elevation.round(3),
            "slope": slope.round(3),
            "drainage_capacity": drainage.round(2),
            "population": pop.round(1),
            "vulnerability_score": vuln.round(4),
            "spatial_block_id": block_id,
        }
    )
    return grids


# ---------------------------------------------------------------------------
# 动态面板
# ---------------------------------------------------------------------------
def generate_panel(
    n_grids: int = 64,
    n_steps: int = 240,
    *,
    seed: int = 42,
    target_rate: float = 0.12,
    dirty: bool = False,
    leaky_column: bool = False,
    start: str | datetime = "2025-06-01 00:00",
    grid_cell_km: float = 0.8,
    label_window_steps: int = 2,
    gap_fraction: float = 0.015,
) -> pd.DataFrame:
    """生成 grid × time 的合成面板（issue_time 锚定口径）。

    时间语义（与 configs/base.yaml 的 task.anchor: issue_time 一致）：
    - 行时间戳 = 预测发起时刻 t；
    - ``flood_label`` = [t, t + label_window_steps) 内是否发生水浸
      （由逐小时瞬时风险聚合而来，末端 window-1 步因右删失丢弃）；
    - ``tide_ast`` = 天文潮，确定性预报量：同一时刻所有网格取值相同，
      任意未来时刻在发起时刻即可精确计算；
    - ``gap_fraction`` 比例的 (grid, hour) 行被随机抽走，模拟缺报 ——
      这让"按时间位移"与"按行位移"产生真实差异，泄漏闸门才有东西可抓。

    注意：target_rate 校准的是**窗口标签率**（人为设定，非现实）。
    """
    rng = np.random.default_rng(seed + 7)
    grids = generate_grids(n_grids, cell_km=grid_cell_km, seed=seed)

    t0 = pd.Timestamp(start)
    times = pd.to_datetime([t0 + timedelta(hours=h) for h in range(n_steps)])

    n = n_grids * n_steps
    g_idx = np.repeat(np.arange(n_grids), n_steps)
    t_idx = np.tile(np.arange(n_steps), n_grids)

    # ---------------- 降雨：基础噪声 + 随机暴雨事件
    base = rng.gamma(shape=1.6, scale=2.2, size=n)
    storm = np.zeros((n_grids, n_steps))
    t = 0
    while t < n_steps:
        if rng.random() < 0.055:
            dur = int(rng.integers(3, 13))
            peak = float(rng.uniform(18.0, 75.0))
            profile = np.sin(np.linspace(0, np.pi, dur + 2))[1:-1] ** 1.4
            end = min(t + dur, n_steps)
            length = end - t
            # 同一场暴雨在不同网格上的强度略有差异
            scales = np.clip(rng.normal(1.0, 0.18, n_grids), 0.5, 1.6)
            storm[:, t:end] = np.maximum(
                storm[:, t:end],
                scales[:, None] * peak * profile[:length][None, :],
            )
            t = end
        else:
            t += 1
    rainfall = np.clip(base + storm.ravel() + rng.normal(0, 0.6, n), 0, None)

    # ---------------- 潮位：天文潮（确定性，全局相位） + 风暴增水（观测）
    phase0 = float(rng.uniform(0, 2 * np.pi))
    tide_ast = 1.15 + 0.88 * np.sin(2 * np.pi * t_idx / 12.42 + phase0)
    surge = (
        0.35 * np.clip(rainfall / 60.0, 0, 1.6)
        + rng.normal(0, 0.07, n)
    )
    # 内陆网格潮位影响衰减（虚构：只给"低洼且靠海"的网格保留潮汐信号）
    coast_fade = np.exp(-grids["y_km"].to_numpy()[g_idx] / 3.0)
    tide = tide_ast + surge * np.clip(coast_fade + 0.25, 0, 1)

    wind = np.clip(1.5 + 0.78 * np.sqrt(rainfall) + rng.normal(0, 0.9, n), 0, None)

    # ---------------- 逐小时瞬时风险 → 窗口标签（issue_time 口径）
    elev = grids["elevation"].to_numpy()[g_idx]
    drain = grids["drainage_capacity"].to_numpy()[g_idx]
    grid_effect = rng.normal(0, 0.55, n_grids)[g_idx]

    p_rain = 1.0 - np.exp(-rainfall / 38.0)
    p_drain = np.clip((45.0 - drain) / 45.0, 0, 1)  # 排水能力越弱，风险越高
    p_tide = np.clip((tide - 1.75) / 0.95, 0, 1.4)
    p_elev = np.clip((16.0 - elev) / 16.0, 0, 1)

    logit = (
        3.9 * p_rain
        + 2.5 * p_tide
        + 2.2 * p_elev
        + 1.1 * p_drain
        + 1.4 * p_rain * p_tide
        + 0.45 * np.clip(wind / 20.0, 0, 1.5)
        + grid_effect
    )
    # 反解截距，使【窗口标签率】命中 target_rate：
    # 窗口概率 q_t = 1 - prod(1 - p_j, j in [t, t+w))
    w = max(1, int(label_window_steps))
    valid = n_steps - w + 1  # 每个网格可用的发起时刻数（末端 w-1 步右删失）

    def _window_rate(shift: float) -> float:
        p = 1.0 / (1.0 + np.exp(-(logit + shift)))
        p_mat = p.reshape(n_grids, n_steps)
        survive = np.ones((n_grids, valid))
        for k in range(w):
            survive *= (1.0 - p_mat[:, k : k + valid])
        return float(np.mean(1.0 - survive))

    shift = _bisect(_window_rate, target_rate)
    p = 1.0 / (1.0 + np.exp(-(logit + shift)))
    p_mat = p.reshape(n_grids, n_steps)
    survive = np.ones((n_grids, valid))
    for k in range(w):
        survive *= (1.0 - p_mat[:, k : k + valid])
    q = 1.0 - survive
    label_mat = (rng.random(q.shape) < q).astype(int)

    # 只保留可定义标签的行：ti < valid（右删失丢弃）
    keep = np.isin(t_idx, np.arange(valid))
    label = np.concatenate([label_mat[i] for i in range(n_grids)])  # 与 keep 行序一致
    label_full = np.full(n, -1, dtype=int)
    label_full[keep] = label

    # ---------------- 抽走部分行模拟缺报（gap）
    keep_idx = np.flatnonzero(keep)
    n_gaps = int(max(1, round(len(keep_idx) * gap_fraction)))
    gap_pos = rng.choice(keep_idx, size=n_gaps, replace=False)
    keep[gap_pos] = False

    df = pd.DataFrame(
        {
            "grid_id": grids["grid_id"].to_numpy()[g_idx][keep],
            "timestamp": times.to_numpy()[t_idx][keep],
            "rainfall": rainfall.round(2)[keep],
            "tide": tide.round(3)[keep],
            "tide_ast": tide_ast.round(4)[keep],
            "wind_speed": wind.round(2)[keep],
            "flood_label": label_full[keep],
            "spatial_block_id": grids["spatial_block_id"].to_numpy()[g_idx][keep],
            "lon": grids["lon"].to_numpy()[g_idx][keep],
            "lat": grids["lat"].to_numpy()[g_idx][keep],
            "x_km": grids["x_km"].to_numpy()[g_idx][keep],
            "y_km": grids["y_km"].to_numpy()[g_idx][keep],
            # 静态属性随网格固定，仅作文档；建模时会被去重为网格级特征
            "elevation": elev.round(3)[keep],
            "slope": grids["slope"].to_numpy()[g_idx][keep],
            "drainage_capacity": drain.round(2)[keep],
            "population": grids["population"].to_numpy()[g_idx][keep],
            "vulnerability_score": grids["vulnerability_score"].to_numpy()[g_idx][keep],
        }
    )

    if leaky_column:
        # 故意制造的泄漏列：把标签信息直接折进特征，用来测试泄漏闸门
        m = len(df)
        df["flood_report_count"] = np.where(
            df["flood_label"].to_numpy() == 1,
            rng.integers(1, 6, m),
            rng.integers(0, 2, m),
        )

    if dirty:
        df = _make_dirty(df, rng)

    df = df.sort_values(["grid_id", "timestamp"]).reset_index(drop=True)
    df.attrs["provenance"] = "SYNTHETIC"
    df.attrs["generator"] = "floodrisk.synthetic.generate_panel"
    return df


# ---------------------------------------------------------------------------
# 静态易发性数据
# ---------------------------------------------------------------------------
def generate_static(
    n_grids: int = 96,
    *,
    seed: int = 42,
    target_rate: float = 0.15,
    dirty: bool = False,
) -> pd.DataFrame:
    """生成"一网格一行"的静态易发性数据（无时间维度）。"""
    rng = np.random.default_rng(seed + 11)
    grids = generate_grids(n_grids, seed=seed)

    elev = grids["elevation"].to_numpy()
    drain = grids["drainage_capacity"].to_numpy()
    slope = grids["slope"].to_numpy()

    logit = (
        2.6 * np.clip((16.0 - elev) / 16.0, 0, 1)
        + 1.7 * np.clip((45.0 - drain) / 45.0, 0, 1)
        - 0.06 * np.clip(slope - 6.0, 0, None)
        + rng.normal(0, 0.5, n_grids)
    )
    logit = logit + _solve_intercept(logit, target_rate)
    prob = 1.0 / (1.0 + np.exp(-logit))
    label = (rng.random(n_grids) < prob).astype(int)

    df = grids.copy()
    df.insert(1, "flood_label", label)
    # 静态模式没有降雨/潮汐的即时观测，用常年气候态代替（明确标注为合成）
    df["rainfall"] = np.clip(rng.gamma(2.0, 3.0, n_grids), 0, None).round(2)
    df["tide"] = (1.15 + rng.normal(0, 0.25, n_grids)).round(3)
    df["wind_speed"] = np.clip(2.0 + rng.gamma(1.5, 1.0, n_grids), 0, None).round(2)

    if dirty:
        df = _make_dirty(df, rng, dynamic=False)

    df.attrs["provenance"] = "SYNTHETIC"
    df.attrs["generator"] = "floodrisk.synthetic.generate_static"
    return df


