def write_geojson(path: str | Path, grids: pd.DataFrame, cell_km: float = 0.8) -> Path:
    """把网格写成方形 Polygon 的 GeoJSON（不依赖 geopandas）。"""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    half = cell_km / 2.0
    features = []
    for row in grids.itertuples(index=False):
        x, y = float(row.x_km), float(row.y_km)
        ring = [
            [x - half, y - half],
            [x + half, y - half],
            [x + half, y + half],
            [x - half, y + half],
            [x - half, y - half],
        ]
        polygon = [
            [
                [_ORIGIN_LON + px / _KM_PER_DEG_LON, _ORIGIN_LAT + py / _KM_PER_DEG_LAT]
                for px, py in ring
            ]
        ]
        features.append(
            {
                "type": "Feature",
                "geometry": {"type": "Polygon", "coordinates": polygon},
                "properties": {
                    "grid_id": str(row.grid_id),
                    "spatial_block_id": str(getattr(row, "spatial_block_id", "")),
                    "elevation": float(getattr(row, "elevation", 0.0)),
                    "provenance": "SYNTHETIC",
                },
            }
        )
    payload = {
        "type": "FeatureCollection",
        "name": "synthetic_grid",
        "note": PROVENANCE_NOTE,
        "features": features,
    }
    p.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return p


def write_provenance_sidecar(data_path: str | Path, extra: dict | None = None) -> Path:
    p = Path(data_path)
    sidecar = p.with_suffix(".provenance.json")
    payload = {
        "provenance": "SYNTHETIC",
        "generator": "floodrisk.synthetic",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "note": PROVENANCE_NOTE,
        "citable": False,
    }
    if extra:
        payload.update(extra)
    sidecar.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return sidecar


def write_synthetic_bundle(
    out_dir: str | Path,
    mode: str = "dynamic",
    *,
    n_grids: int = 64,
    n_steps: int = 240,
    seed: int = 42,
    dirty: bool = False,
) -> dict[str, Path]:
    """一键生成一套可跑通的合成数据集（数据 + provenance + 网格几何）。"""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    grids = generate_grids(n_grids, seed=seed)
    paths: dict[str, Path] = {}

    if mode == "dynamic":
        df = generate_panel(n_grids, n_steps, seed=seed, dirty=dirty)
        data_path = out / ("panel_synthetic_dirty.csv" if dirty else "panel_synthetic.csv")
    else:
        df = generate_static(n_grids, seed=seed, dirty=dirty)
        data_path = out / ("static_synthetic_dirty.csv" if dirty else "static_synthetic.csv")

    df.to_csv(data_path, index=False)
    paths["data"] = data_path
    paths["provenance"] = write_provenance_sidecar(
        data_path,
        {"mode": mode, "n_grids": n_grids, "n_steps": n_steps if mode == "dynamic" else 1},
    )
    paths["grid_layer"] = write_geojson(out / "grids_synthetic.geojson", grids)
    return paths


# ---------------------------------------------------------------------------
# 内部
# ---------------------------------------------------------------------------
def _bisect(fn, target: float, lo: float = -30.0, hi: float = 30.0, iters: int = 80) -> float:
    """单调函数反解：找 shift 使 fn(shift) == target。"""
    target = float(np.clip(target, 0.01, 0.99))
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        if fn(mid) > target:
            hi = mid
        else:
            lo = mid
    return 0.5 * (lo + hi)


def _solve_intercept(logit: np.ndarray, target_rate: float) -> float:
    """二分反解截距，使平均瞬时预测概率等于目标率。

    注意：这等于**人为设定**正例率。真实数据的正例率由历史记录决定，
    不能搬这个数字去预期现实。
    """
    return _bisect(lambda s: float(np.mean(1.0 / (1.0 + np.exp(-(logit + s))))), target_rate)


def _make_dirty(df: pd.DataFrame, rng: np.random.Generator, dynamic: bool = True) -> pd.DataFrame:
    """注入缺失、越界与重复，用于测试校验器。"""
    df = df.copy()
    n = len(df)

    for col, frac in (("rainfall", 0.02), ("tide", 0.01), ("wind_speed", 0.03)):
        if col in df.columns:
            idx = rng.choice(n, size=max(1, int(n * frac)), replace=False)
            df.loc[df.index[idx], col] = np.nan

    if "tide" in df.columns:
        idx = rng.choice(n, size=max(1, int(n * 0.004)), replace=False)
        df.loc[df.index[idx], "tide"] = -3.5  # 明显越界

    if dynamic:
        dup_idx = rng.choice(n, size=max(1, int(n * 0.01)), replace=False)
        df = pd.concat([df, df.iloc[dup_idx]], ignore_index=True)
    return df
